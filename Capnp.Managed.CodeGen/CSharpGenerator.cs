using System.Collections.Immutable;
using System.Text;
using Capnp.Managed.Schema;

namespace Capnp.Managed.CodeGen;

public sealed record GeneratedFile(string Name, string Text);

/// <summary>Emits deterministic C# bindings from compiler-supplied layouts.</summary>
public static class CSharpGenerator
{
    public static ImmutableArray<GeneratedFile> Generate(SchemaRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);
        Analysis analysis = new(request);
        analysis.Check();
        ImmutableArray<GeneratedFile>.Builder result = ImmutableArray.CreateBuilder<GeneratedFile>(request.Files.Length);
        int remaining = 32 * 1024 * 1024;
        foreach (RequestedFile requested in request.Files.OrderBy(file => file.Name, StringComparer.Ordinal))
        {
            SchemaNode file = analysis.Resolve(requested.Id);
            Emitter emitter = new(analysis);
            string ns = Analysis.Namespace(file);
            string text = emitter.Emit(ns, analysis.Declarations(file.Id));
            remaining -= text.Length;
            if (remaining < 0)
            {
                throw new InvalidDataException("Generated source exceeds the request output limit.");
            }

            result.Add(new(ns + ".g.cs", text));
        }

        return result.MoveToImmutable();
    }
}

internal sealed partial class Emitter(Analysis analysis)
{
    private readonly StringBuilder source = new();
    private int indentation;

    internal string Emit(string ns, IEnumerable<SchemaNode> declarations)
    {
        Line("// <auto-generated/>");
        Line("#nullable enable");
        Line("using System;");
        Line("using Capnp.Managed;");
        Line($"namespace {ns};");
        foreach (SchemaNode node in declarations)
        {
            Line();
            switch (node.Kind)
            {
                case SchemaKind.Enum: Enumeration(node); break;
                case SchemaKind.Struct: Structure(node); break;
                case SchemaKind.Constant: Constant(node); break;
                case SchemaKind.Annotation: break;
                case SchemaKind.File or SchemaKind.Interface: throw Analysis.Unsupported(node, "unexpected declaration");
                default: throw Analysis.Unsupported(node, "unrecognized declaration");
            }
        }

        return source.ToString();
    }

    private void Enumeration(SchemaNode node)
    {
        Open($"public enum {analysis.Local(node)} : ushort");
        HashSet<string> members = new(StringComparer.Ordinal) { "Value__", analysis.Local(node) };
        for (int i = 0; i < node.Enumerants.Length; i++)
        {
            string name = Analysis.Name(node.Enumerants[i]);
            Analysis.Claim(members, name, node.DisplayName);
            Line($"{name} = {i},");
        }

        Close();
    }

    private void Structure(SchemaNode node)
    {
        string name = analysis.Local(node);
        Open($"public static partial class {name}");
        HashSet<string> typeMembers = new(StringComparer.Ordinal)
        {
            name, "SchemaId", "Layout", "Reader", "Builder", "Variant", "ReadRoot", "InitRoot",
            "ToString", "Equals", "GetType", "GetHashCode", "MemberwiseClone", "Finalize"
        };
        if (name is "Reader" or "Builder" or "Variant" or "SchemaId" or "Layout" or "ReadRoot" or "InitRoot")
        {
            throw Analysis.Unsupported(node, "type name is reserved for the generated API");
        }

        Line($"public const ulong SchemaId = {Hex(node.Id)};");
        if (!node.IsGroup)
        {
            Line($"public static StructLayout Layout => new({node.DataWords}, {node.PointerWords});");
            Line("public static Reader ReadRoot(MessageReader message) => new(message.Root.AsStruct());");
            Line("public static Builder InitRoot(MessageBuilder message) => new(message.InitRoot(Layout));");
        }

        if (node.DiscriminantCount > 0)
        {
            Open("public enum Variant : ushort");
            foreach (SchemaField field in node.Fields.Where(InUnion).OrderBy(field => field.Discriminant))
            {
                string variant = Analysis.Name(field.Name);
                if (variant == "Variant")
                {
                    throw Analysis.Unsupported(node, "union member collides with Variant");
                }

                Line($"{variant} = {field.Discriminant},");
            }

            Close();
        }

        foreach (SchemaField field in node.Fields)
        {
            string member = Analysis.Name(field.Name);
            if (field.Default.PointerHex is string hex)
            {
                DefaultStorage(member, hex);
            }

            if (field.Type.Kind == ValueKind.List)
            {
                ListTypes(field.Type.Element!, member, typeMembers, node.DisplayName);
            }
        }

        Open("public readonly ref struct Reader");
        Line("private readonly StructReader wire;");
        Line("public Reader(StructReader wire) => this.wire = wire;");
        if (node.DiscriminantCount > 0)
        {
            Line($"public Variant Which => (Variant)wire.ReadScalar({node.DiscriminantOffset * 16}, 16);");
        }

        HashSet<string> readerMembers = Members("Reader");
        foreach (SchemaField field in node.Fields)
        {
            ReadField(node, field, readerMembers);
        }

        Close();
        Open("public readonly ref struct Builder");
        Line("private readonly StructBuilder wire;");
        Line("public Builder(StructBuilder wire) => this.wire = wire;");
        if (node.DiscriminantCount > 0)
        {
            Open("private void Select(ushort variant)");
            ClearFields(node.Fields.Where(InUnion));
            Line($"wire.SetScalar({node.DiscriminantOffset * 16}, 16, variant);");
            Close();
        }

        HashSet<string> builderMembers = Members("Builder");
        foreach (SchemaField field in node.Fields)
        {
            WriteField(node, field, builderMembers);
        }

        Close();
        Close();
    }

    private static HashSet<string> Members(string type) => new(StringComparer.Ordinal)
    {
        type, "Which", "Select", "ToString", "Equals", "GetType", "GetHashCode", "MemberwiseClone", "Finalize"
    };

    private void ReadField(SchemaNode node, SchemaField field, HashSet<string> members)
    {
        string name = Analysis.Name(field.Name);
        string tag = InUnion(field) ? $"Which == Variant.{name}" : "true";
        if (field.Group != 0)
        {
            Analysis.Claim(members, name, node.DisplayName);
            string type = analysis.Qualified(field.Group) + ".Reader";
            Line($"public {type} {name} => {ReadGuard($"new {type}(wire)", tag)};");
            return;
        }

        if (field.Type.Kind == ValueKind.Void)
        {
            Analysis.Claim(members, "Is" + name, node.DisplayName);
            Line($"public bool Is{name} => {tag};");
            return;
        }

        int width = Analysis.Width(field.Type.Kind);
        if (width > 0)
        {
            Analysis.Claim(members, name, node.DisplayName);
            string read = $"wire.ReadScalar({field.Offset * width}, {width}, {Hex(field.Default.Bits)})";
            Line($"public {TypeName(field.Type)} {name} => {ReadGuard(FromBits(field.Type, read), tag)};");
            return;
        }

        string slot = ReadGuard($"wire.GetPointer({field.Offset})", tag);
        Analysis.Claim(members, "Has" + name, node.DisplayName);
        Line($"public bool Has{name} => !({slot}).IsNull;");
        string fallback = field.Default.PointerHex is null ? "" : $"Default{name}";
        if (field.Type.Kind == ValueKind.Text)
        {
            Analysis.Claim(members, name + "Utf8", node.DisplayName);
            Analysis.Claim(members, "Decode" + name, node.DisplayName);
            Line($"public ReadOnlySpan<byte> {name}Utf8 => ({slot}).AsText({fallback});");
            Line($"public string? Decode{name}() => ({slot}).DecodeText({fallback});");
        }
        else
        {
            Analysis.Claim(members, name, node.DisplayName);
            Line($"public {PointerType(field.Type, name)} {name} => {ReadPointer(field.Type, $"({slot})", name, fallback)};");
        }
    }

    private void WriteField(SchemaNode node, SchemaField field, HashSet<string> members)
    {
        string name = Analysis.Name(field.Name);
        string select = InUnion(field) ? $"Select({field.Discriminant}); " : "";
        string slot = $"wire.GetPointer({field.Offset})";
        int width = Analysis.Width(field.Type.Kind);
        if (field.Group != 0)
        {
            Analysis.Claim(members, "Init" + name, node.DisplayName);
            SchemaNode group = analysis.Resolve(field.Group);
            string type = analysis.Qualified(field.Group) + ".Builder";
            Open($"public {type} Init{name}()");
            if (select.Length > 0)
            {
                Line(select.TrimEnd());
            }
            else
            {
                ClearGroup(group);
            }

            Line($"return new {type}(wire);");
            Close();
        }
        else if (field.Type.Kind == ValueKind.Void)
        {
            Analysis.Claim(members, "Select" + name, node.DisplayName);
            Line($"public void Select{name}() {{ {select}}}");
        }
        else if (width > 0)
        {
            Analysis.Claim(members, "Set" + name, node.DisplayName);
            Line($"public void Set{name}({TypeName(field.Type)} value) {{ {select}wire.SetScalar({field.Offset * width}, {width}, {ToBits(field.Type)}, {Hex(field.Default.Bits)}); }}");
        }
        else
        {
            PointerWrite(field.Type, name, slot, select, members, node.DisplayName);
            Analysis.Claim(members, "Clear" + name, node.DisplayName);
            Line($"public void Clear{name}() {{ {select}{slot}.Clear(); }}");
            if (field.Default.PointerHex is not null)
            {
                Analysis.Claim(members, "Set" + name + "ToDefault", node.DisplayName);
                Line($"public void Set{name}ToDefault() {{ {select}{slot}.SetCopy(Default{name}); }}");
            }
        }
    }

    private void ClearFields(IEnumerable<SchemaField> fields)
    {
        SortedSet<(uint Offset, int Width)> slots = [];
        foreach (SchemaField field in fields)
        {
            CollectClears(field, slots);
        }

        foreach ((uint offset, int width) in slots)
        {
            Line(width < 0 ? $"wire.GetPointer({offset}).Clear();" : $"wire.SetScalar({offset}, {width}, 0);");
        }
    }

    private void CollectClears(SchemaField field, SortedSet<(uint Offset, int Width)> slots)
    {
        if (field.Group != 0)
        {
            SchemaNode group = analysis.Resolve(field.Group);
            if (group.DiscriminantCount != 0)
            {
                _ = slots.Add((group.DiscriminantOffset * 16, 16));
            }

            foreach (SchemaField nested in group.Fields)
            {
                CollectClears(nested, slots);
            }
        }
        else if (Analysis.Width(field.Type.Kind) is int width && width != 0)
        {
            _ = slots.Add((width < 0 ? field.Offset : field.Offset * (uint)width, width));
        }
    }

    private void ClearGroup(SchemaNode group)
    {
        if (group.DiscriminantCount != 0)
        {
            Line($"wire.SetScalar({group.DiscriminantOffset * 16}, 16, 0);");
        }

        ClearFields(group.Fields);
    }

    private void Constant(SchemaNode node)
    {
        SchemaType type = node.ConstantType!;
        SchemaValue value = node.ConstantValue!;
        string name = analysis.Local(node);
        if (name is "Value" or "DefaultValue")
        {
            throw Analysis.Unsupported(node, "constant type name collides with a generated member");
        }

        Open($"public static class {name}");
        if (value.PointerHex is string hex)
        {
            DefaultStorage("Value", hex);
        }

        if (type.Kind == ValueKind.List)
        {
            ListTypes(type.Element!, "Value", new(StringComparer.Ordinal), node.DisplayName);
        }

        if (Analysis.Width(type.Kind) > 0)
        {
            Line($"public static {TypeName(type)} Value => {FromBits(type, Hex(value.Bits))};");
        }
        else if (type.Kind != ValueKind.Void)
        {
            string pointer = value.PointerHex is null ? "default(PointerReader)" : "DefaultValue";
            Line($"public static {PointerType(type, "Value")} Value => {ReadPointer(type, pointer, "Value", "")};");
        }

        Close();
    }

    private void DefaultStorage(string name, string hex)
    {
        Line($"private static readonly byte[] default{name} = Convert.FromHexString(");
        indentation++;
        for (int offset = 0; offset < hex.Length; offset += 128)
        {
            int length = Math.Min(128, hex.Length - offset);
            Line($"\"{hex.Substring(offset, length)}\"{(offset + length == hex.Length ? ");" : " +")}");
        }

        indentation--;
        Line($"private static PointerReader Default{name} => new MessageReader(default{name}).Root;");
    }

    private static bool InUnion(SchemaField field) => field.Discriminant != ushort.MaxValue;
    private static string ReadGuard(string value, string tag) => tag == "true" ? value :
        $"({tag} ? {value} : throw new InvalidOperationException(\"Inactive union member.\"))";
    private static string Hex(ulong bits) => $"0x{bits:X}UL";
    private void Open(string header) { Line(header); Line("{"); indentation++; }
    private void Close() { indentation--; Line("}"); }
    private void Line(string line = "")
    {
        int spaces = line.Length == 0 ? 0 : indentation * 4;
        if ((long)source.Length + spaces + line.Length + 1 > 16 * 1024 * 1024)
        {
            throw new InvalidDataException("Generated file exceeds the output limit.");
        }

        _ = source.Append(' ', spaces).Append(line).Append('\n');
    }
}
