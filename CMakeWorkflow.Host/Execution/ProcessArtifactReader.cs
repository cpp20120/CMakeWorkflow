using System.Security.Cryptography;

namespace CMakeWorkflow.Host;

// Process-domain catalog over the same descriptor-anchored, no-follow artifact
// reader as CMake. Never accept an arbitrary client path as a download request.
internal static class ProcessArtifactReader
{
    private sealed record Candidate(string Id, string Kind, string? NodeId, string Leaf);

    internal static bool IsProcess(WorkspaceReadPaths paths, string operationId)
    {
        var db = Path.Combine(paths.WorkspaceDirectory, ".cmakeworkflow", "operations.sqlite");
        paths.Require(db);
        if (!File.Exists(db)) return false;
        using var store = new DurableAcceptanceStore(paths.WorkspaceDirectory, readOnly: true);
        return store.Get(operationId) is not null && store.GetDomainKind(operationId) == "process";
    }

    private static List<Candidate> Candidates(ProcessOperationReport report)
    {
        var items = new List<Candidate> { new("report", "report", null, "run.json") };
        foreach (var node in report.Nodes)
        {
            if (node.Stdout is not null) items.Add(new("stdout:" + node.Id, "stdout", node.Id, node.Stdout));
            if (node.Stderr is not null) items.Add(new("stderr:" + node.Id, "stderr", node.Id, node.Stderr));
        }
        if (items.Count > 512) throw new ApplicationRefusal("resource_limit", "Too many process artifacts.");
        return items;
    }

    private static string PathFor(WorkspaceReadPaths paths, string directory, Candidate candidate)
    {
        // Logs are generated by the Host, not arbitrary user-provided artifact paths.
        if (string.IsNullOrWhiteSpace(candidate.Leaf) ||
            candidate.Leaf != Path.GetFileName(candidate.Leaf) ||
            candidate.Leaf == "." || candidate.Leaf == "..")
            throw new ApplicationRefusal("path_not_allowed", "Invalid process artifact name.");
        return paths.Require(Path.Combine(directory, candidate.Leaf));
    }

    internal static async Task<OperationArtifactList> ListAsync(WorkspaceReadPaths paths,
        string operationId, CancellationToken ct)
    {
        var (report, directory, revision) =
            await ProcessOperationReportReader.ReadVerifiedAsync(paths, operationId, ct);
        var entries = new List<OperationArtifactInfo>();
        foreach (var candidate in Candidates(report))
        {
            ct.ThrowIfCancellationRequested();
            var path = PathFor(paths, directory, candidate);
            FileStream file;
            try { file = OperationArtifactFile.OpenRead(paths.WorkspaceDirectory, path); }
            catch (FileNotFoundException) when (candidate.Id != "report") { continue; }
            catch (DirectoryNotFoundException) when (candidate.Id != "report") { continue; }
            await using var opened = file;
            var size = file.Length;
            var stamp = File.GetLastWriteTimeUtc(file.SafeFileHandle).Ticks;
            var hash = Convert.ToHexString(await SHA256.HashDataAsync(file, ct));
            if (size != file.Length || stamp != File.GetLastWriteTimeUtc(file.SafeFileHandle).Ticks)
                throw new ApplicationRefusal("artifact_changed", "Process artifact changed during discovery.");
            entries.Add(new(candidate.Id, candidate.Kind, candidate.NodeId, candidate.Leaf,
                size, stamp, hash));
        }
        return new(operationId, revision, entries);
    }

    internal static async Task<OperationArtifactChunk> ReadChunkAsync(WorkspaceReadPaths paths,
        OperationArtifactChunkRequest request, CancellationToken ct)
    {
        if (request.Count is < 1 or > OperationArtifactReader.MaximumChunkBytes || request.Offset < 0 ||
            request.ExpectedSize < 0 || request.ExpectedLastWriteUtcTicks < 0 ||
            request.Offset > request.ExpectedSize)
            throw new ArgumentException("Invalid process artifact range.");
        var (report, directory, _) =
            await ProcessOperationReportReader.ReadVerifiedAsync(paths, request.OperationId, ct);
        var selected = Candidates(report).FirstOrDefault(c => c.Id == request.ArtifactId)
                       ?? throw new ApplicationRefusal("not_found", "Unknown process artifact.");
        var path = PathFor(paths, directory, selected);
        await using var file = OperationArtifactFile.OpenRead(paths.WorkspaceDirectory, path);
        var size = file.Length;
        var stamp = File.GetLastWriteTimeUtc(file.SafeFileHandle).Ticks;
        if (size != request.ExpectedSize || stamp != request.ExpectedLastWriteUtcTicks)
            throw new ApplicationRefusal("artifact_changed", "Process artifact changed after discovery.");
        var count = (int)Math.Min(request.Count, size - request.Offset);
        var bytes = new byte[count];
        file.Seek(request.Offset, SeekOrigin.Begin);
        await file.ReadExactlyAsync(bytes, ct);
        if (size != file.Length || stamp != File.GetLastWriteTimeUtc(file.SafeFileHandle).Ticks)
            throw new ApplicationRefusal("artifact_changed", "Process artifact changed during transfer.");
        return new(selected.Id, request.Offset, size, stamp, bytes, request.Offset + count == size);
    }
}
